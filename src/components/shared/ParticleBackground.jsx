function SwarmPoints() {
  const meshRef = useRef();
  const count = Math.floor(POS_DATA.length / 3);

  const target = useMemo(() => new THREE.Vector3(), []);
  const pColor = useMemo(() => new THREE.Color(), []);

  const [geometry] = useMemo(() => {
    const geo = new THREE.BufferGeometry();
    const pos = new Float32Array(POS_DATA);
    const cols = new Float32Array(count * 3);

    geo.setAttribute('position', new THREE.BufferAttribute(pos, 3));
    geo.setAttribute('color', new THREE.BufferAttribute(cols, 3));

    return [geo, cols];
  }, [count]);

  const texture = useMemo(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 16;
    canvas.height = 16;
    const ctx = canvas.getContext('2d');
    const grad = ctx.createRadialGradient(8, 8, 0, 8, 8, 8);
    grad.addColorStop(0, 'rgba(255,255,255,1)');
    grad.addColorStop(0.35, 'rgba(245,208,97,0.85)');
    grad.addColorStop(0.7, 'rgba(0,114,255,0.4)');
    grad.addColorStop(1, 'rgba(0,0,0,0)');
    ctx.fillStyle = grad;
    ctx.beginPath();
    ctx.arc(8, 8, 8, 0, Math.PI * 2);
    ctx.fill();
    return new THREE.CanvasTexture(canvas);
  }, []);

  useFrame((state) => {
    if (!meshRef.current) return;
    const time = state.clock.getElapsedTime() * 0.75;
    const posAttr = geometry.attributes.position;
    const colAttr = geometry.attributes.color;

    for (let i = 0; i < count; i++) {
      const origX = POS_DATA[i * 3];
      const origY = POS_DATA[i * 3 + 1];
      const origZ = POS_DATA[i * 3 + 2];

      const normIdx = i / count;
      const waveX = Math.sin(time * 1.4 + origY * 0.05 + i * 0.1) * 1.3;
      const waveY = Math.cos(time * 1.2 + origX * 0.05 + i * 0.05) * 1.3;
      const waveZ = Math.sin(time * 1.8 + i) * 2.2;

      target.set(origX + waveX, origY + waveY, origZ + waveZ);

      // Color spectrum cycling between Metallic Gold (#F5D061), Royal Sapphire Blue (#0052FF), and Cyan (#00D2FF)
      const colorPhase = Math.sin(time * 0.5 + normIdx * 6.28);
      let hue, sat, light;

      if (colorPhase > 0.2) {
        // Gold palette (#F5D061)
        hue = 0.12 + Math.sin(normIdx * 3.0) * 0.03;
        sat = 0.95;
        light = 0.5 + Math.sin(time + i * 0.1) * 0.2;
      } else if (colorPhase > -0.4) {
        // Royal Sapphire Blue palette (#0052FF)
        hue = 0.60 + Math.cos(normIdx * 2.0) * 0.04;
        sat = 0.9;
        light = 0.45 + Math.sin(time * 1.2 + i * 0.15) * 0.2;
      } else {
        // Electric Cyan palette (#00D2FF)
        hue = 0.50 + Math.sin(time * 0.8) * 0.03;
        sat = 0.95;
        light = 0.5 + Math.cos(time + i) * 0.25;
      }

      pColor.setHSL(hue, sat, Math.min(0.85, Math.max(0.25, light)));

      posAttr.setXYZ(i, target.x, target.y, target.z);
      colAttr.setXYZ(i, pColor.r, pColor.g, pColor.b);
    }

    posAttr.needsUpdate = true;
    colAttr.needsUpdate = true;

    meshRef.current.rotation.y = time * 0.035;
    meshRef.current.rotation.x = Math.sin(time * 0.02) * 0.08;
  });

  return (
    <points ref={meshRef} geometry={geometry}>
      <pointsMaterial
        size={0.75}
        vertexColors
        map={texture}
        transparent
        opacity={0.7}
        blending={THREE.AdditiveBlending}
        depthWrite={false}
      />
    </points>
  );
}

